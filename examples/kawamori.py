def draw_char(char, x0, y0, width, height):
    for px, py in FONT[char]:
        tx = x0 + px * width
        ty = y0 + py * height

        move_to(tx, ty)


def draw_text(
    text,
    center_x,
    center_y,
    width=50.0,
    height=80.0,
    gap=12.0,
):
    total_width = (
        len(text) * width
        + (len(text) - 1) * gap
    )

    x0 = center_x - total_width / 2.0
    y0 = center_y - height / 2.0

    for char in text:
        print(f"Drawing: {char}")

        draw_char(
            char,
            x0,
            y0,
            width,
            height,
        )

        x0 += width + gap



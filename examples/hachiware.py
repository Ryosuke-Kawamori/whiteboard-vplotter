from vplotter_motion import (
    setup,
    cleanup,
    move_to,
    MOTOR_SPACING,
)


def draw_hachiware(cx, cy, scale=2.0):
    """
    ハチワレ風 一筆書き

    scale=1.0 で横幅だいたい 320mm くらい
    scale=2.0 でかなり大きめ
    """

    def p(dx, dy):
        return (
            cx + dx * scale,
            cy + dy * scale,
        )

    path = [
        # 左耳
        p(-110, -20),
        p(-145, -105),
        p(-75, -65),

        # 頭の上
        p(-35, -92),
        p(0, -100),
        p(35, -92),

        # 右耳
        p(75, -65),
        p(145, -105),
        p(110, -20),

        # 顔の右輪郭
        p(135, 20),
        p(120, 60),
        p(90, 90),
        p(45, 110),
        p(0, 118),

        # 顔の左輪郭
        p(-45, 110),
        p(-90, 90),
        p(-120, 60),
        p(-135, 20),
        p(-110, -20),

        # おでこのハチワレ模様（左）
        p(-55, -30),
        p(-18, -75),
        p(0, -48),

        # おでこのハチワレ模様（右）
        p(18, -75),
        p(55, -30),
        p(18, -8),
        p(0, -48),
        p(-18, -8),
        p(-55, -30),

        # 左目
        p(-58, 6),
        p(-42, 0),
        p(-28, 8),
        p(-42, 16),
        p(-58, 6),

        # 鼻
        p(0, 26),

        # 右目
        p(28, 8),
        p(42, 0),
        p(58, 6),
        p(42, 16),
        p(28, 8),

        # 鼻を三角っぽく
        p(0, 26),
        p(-10, 35),
        p(0, 42),
        p(10, 35),
        p(0, 26),

        # 口
        p(-14, 54),
        p(-4, 62),
        p(0, 56),
        p(4, 62),
        p(14, 54),

        # 右ほっぺ＆右ひげ
        p(48, 44),
        p(120, 30),
        p(52, 50),
        p(132, 54),
        p(54, 58),
        p(120, 76),

        # あご中央へ
        p(0, 72),

        # 左ほっぺ＆左ひげ
        p(-54, 58),
        p(-132, 54),
        p(-52, 50),
        p(-120, 30),
        p(-48, 44),
        p(-120, 76),

        # 最後に口元へ戻る
        p(0, 72),
    ]

    print("Drawing HACHIWARE-ish face")

    for px, py in path:
        move_to(px, py)


if __name__ == "__main__":
    setup()

    try:
        cx = MOTOR_SPACING / 2.0
        cy = 450.0

        draw_hachiware(
            cx,
            cy,
            scale=1.8,
        )

        print("DONE : HACHIWARE")

    finally:
        cleanup()